//! Типы секретов.
//!
//! Каждый секрет — отдельный тип, а не `[u8; 32]`, по двум причинам. Первая:
//! перепутать местами `SecretA` и `SecretB` в вызове ключевой схемы становится
//! ошибкой компиляции, а не тихой уязвимостью. Вторая: фиксированная длина
//! задана типом, а не соглашением, и это обязательное условие корректности
//! комбинатора `HKDF-Extract` над конкатенацией — при переменной длине
//! кодирование стало бы неоднозначным.
//!
//! `Debug` у всех типов редактирован. Секрет, попавший в лог или в отчёт о
//! панике, утекает ровно так же, как записанный на диск.

use core::fmt;
use rand_core::CryptoRng;
use zeroize::{Zeroize, ZeroizeOnDrop};

/// Длина всех секретов схемы.
pub const SECRET_LEN: usize = 32;

macro_rules! secret_type {
    ($(#[$meta:meta])* $name:ident) => {
        $(#[$meta])*
        #[derive(Clone, Zeroize, ZeroizeOnDrop)]
        pub struct $name([u8; SECRET_LEN]);

        impl $name {
            /// Взять готовые байты под контроль.
            pub fn from_bytes(bytes: [u8; SECRET_LEN]) -> Self {
                Self(bytes)
            }

            /// Сгенерировать из переданного генератора.
            ///
            /// Генератор передаётся аргументом, а не берётся из окружения:
            /// иначе тесты перестают быть детерминированными, а векторы
            /// Wycheproof нельзя прогнать через собственные места вызова.
            pub fn random<R: CryptoRng + ?Sized>(rng: &mut R) -> Self {
                let mut bytes = [0u8; SECRET_LEN];
                rng.fill_bytes(&mut bytes);
                let secret = Self(bytes);
                // Массив на стеке — вторая копия секрета, и `ZeroizeOnDrop`
                // самого типа её не покрывает: обёрнут результат, а не
                // заготовка, из которой он собран.
                bytes.zeroize();
                secret
            }

            /// Открыть байты. Вызов намеренно многословен: он должен бросаться в
            /// глаза при чтении кода и при ревью.
            pub fn expose(&self) -> &[u8; SECRET_LEN] {
                &self.0
            }
        }

        impl fmt::Debug for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                write!(f, concat!(stringify!($name), "(<секрет скрыт>)"))
            }
        }
    };
}

secret_type! {
    /// Ключ содержимого. Случаен и не выводится ни из чего: он **заворачивается**
    /// под KEK, а не порождается им. Ровно это позволяет позже добавить второго
    /// получателя, ключ восстановления или ротацию, не ломая ранее выпущенные
    /// файлы.
    Cek
}

secret_type! {
    /// Ключ заворачивания, выведенный из обоих секретов схемы 2-из-2.
    Kek
}

secret_type! {
    /// Доля сервера. Запечатана на ключ сервера лицензий и лежит в контейнере.
    SecretA
}

secret_type! {
    /// Доля получателя. В бесшовном режиме доступна любому, у кого есть файл, —
    /// и это осознанная цена бесшовности, зафиксированная в спецификации.
    SecretB
}

secret_type! {
    /// Ключ шифрования полезной нагрузки, выведенный из CEK и соли заголовка.
    PayloadKey
}

secret_type! {
    /// Ключ MAC изменяемой области.
    MacKey
}

secret_type! {
    /// Ключ MAC сессии (K24): отделён от ключа изменяемой области.
    SessionMacKey
}

secret_type! {
    /// Ключ приватных метаданных (K5): настоящее имя файла и справочный размер.
    ///
    /// Отдельный тип, а не [`PayloadKey`], хотя длина и способ вывода те же.
    /// Обещание этого модуля — «перепутать местами в вызове ключевой схемы
    /// становится ошибкой компиляции» — на пару K3/K5 не распространялось: обе
    /// производные возвращали `PayloadKey`, и ключ метаданных молча принимался
    /// на месте ключа полезной нагрузки. Разделение доменов при этом держалось
    /// (метки разные, значения разные), то есть тихой уязвимости не возникало, —
    /// но защита была заявлена сильнее, чем есть, а это и есть тот случай, ради
    /// которого типы здесь вообще заведены.
    MetaKey
}

secret_type! {
    /// Одноразовый код-претензия.
    ///
    /// Энтропия не ниже [`crate::MIN_CLAIM_BITS`]. Это не косметическое
    /// требование: XChaCha20-Poly1305 не является key-committing, и код низкой
    /// энтропии восстанавливается через оракул разбиения существенно быстрее
    /// полного перебора.
    ClaimSecret
}

secret_type! {
    /// Приватный ключ X25519 для запечатывания слотов.
    X25519Secret
}

/// Буфер под открытый текст, затирающий себя и не растущий.
///
/// Не `Zeroizing<Vec<u8>>`, и разница здесь принципиальная. `Zeroizing` затирает
/// содержимое **при уничтожении**, но ничего не может сделать при росте: когда
/// `Vec` перевыделяет память, старый буфер отдаётся аллокатору как есть, со всем
/// уже накопленным открытым текстом. Файл, расшифрованный в растущий вектор,
/// оставляет в куче свои копии на каждом удвоении ёмкости.
///
/// Поэтому ёмкость здесь задаётся один раз и не меняется, а сам массив всегда
/// имеет полную длину: затирать нужно и «хвост» за границей значимых данных,
/// иначе остатки предыдущего, более длинного чанка переживут запись более
/// короткого.
///
/// Тип обязателен в сигнатуре [`crate::aead::open_chunk`] намеренно. Раньше туда
/// принимался обычный `Vec<u8>`, и гарантия затирания держалась на дисциплине
/// вызывающего — то есть не держалась ни на чём.
pub struct SecretBuf {
    /// Длина всегда равна ёмкости: так затирание покрывает и незначимый хвост.
    bytes: Vec<u8>,
    /// Сколько байт от начала значимы.
    len: usize,
}

impl SecretBuf {
    /// Выделить буфер заданной ёмкости. Расти он не будет.
    pub fn with_capacity(capacity: usize) -> Self {
        Self { bytes: vec![0u8; capacity], len: 0 }
    }

    /// Ёмкость, заданная при создании.
    pub fn capacity(&self) -> usize {
        self.bytes.len()
    }

    /// Число значимых байт.
    pub fn len(&self) -> usize {
        self.len
    }

    pub fn is_empty(&self) -> bool {
        self.len == 0
    }

    /// Значимые байты.
    pub fn as_slice(&self) -> &[u8] {
        self.bytes.get(..self.len).unwrap_or_default()
    }

    /// Всё место буфера под запись извне — например, под чтение из файла.
    ///
    /// Буфер **затирается перед выдачей**. Без этого пара «взять место —
    /// объявить длину» отдавала бы наружу чужие байты: вызывающий, записавший
    /// сто байт и объявивший двести, получил бы сто байт своих и сто байт
    /// предыдущего, более длинного содержимого. Для буфера, через который течёт
    /// расшифрованный документ, это означает выдачу куска соседнего чанка.
    ///
    /// После записи вызывающий объявляет длину через [`SecretBuf::declare_len`].
    /// Объявив больше, чем записал, он получит нули — не чужой открытый текст.
    pub fn as_capacity_mut(&mut self) -> &mut [u8] {
        self.wipe();
        &mut self.bytes
    }

    /// Объявить, сколько байт значимо. Больше ёмкости — отказ, а не рост.
    pub fn declare_len(&mut self, len: usize) -> Result<(), crate::CryptoError> {
        if len > self.capacity() {
            return Err(crate::CryptoError::BadLength);
        }
        self.len = len;
        Ok(())
    }

    /// Значимые байты на запись — для преобразования содержимого НА МЕСТЕ.
    ///
    /// Отличается от [`SecretBuf::as_capacity_mut`] двумя вещами, и обе
    /// существенны: возвращается только объявленная часть, и буфер **не**
    /// затирается перед выдачей. Ровно это нужно расшифровке на месте: в буфере
    /// уже лежит шифротекст, и стереть его перед расшифровкой значило бы стереть
    /// вход.
    ///
    /// Заведена не ради удобства. Без неё расшифровка обязана была выделять
    /// вектор под открытый текст и копировать его сюда — то есть каждый
    /// расшифрованный чанк проходил через обычную кучу, а страницы обычной кучи
    /// уезжают в файл подкачки. Просмотрщик запирает свою память
    /// (`VirtualLock`), и промежуточная копия сводила бы это на нет.
    pub fn as_declared_mut(&mut self) -> &mut [u8] {
        let len = self.len;
        self.bytes.get_mut(..len).unwrap_or_default()
    }

    /// Заменить содержимое копией `src`.
    pub fn fill_from(&mut self, src: &[u8]) -> Result<(), crate::CryptoError> {
        // Затирание перед записью, а не только длина: без него хвост от более
        // длинной предыдущей записи остался бы в буфере и дожил бы до конца
        // работы, хотя логически его уже нет.
        self.wipe();
        let room = self.bytes.get_mut(..src.len()).ok_or(crate::CryptoError::BadLength)?;
        room.copy_from_slice(src);
        self.len = src.len();
        Ok(())
    }

    /// Затереть всё содержимое, включая незначимый хвост.
    pub fn wipe(&mut self) {
        self.bytes.zeroize();
        // `Vec::zeroize` обнуляет длину, а нам нужна полная — восстанавливаем.
        self.bytes.resize(self.bytes.capacity(), 0);
        self.len = 0;
    }
}

impl Drop for SecretBuf {
    fn drop(&mut self) {
        self.bytes.zeroize();
    }
}

impl fmt::Debug for SecretBuf {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "SecretBuf({} байт, содержимое скрыто)", self.len)
    }
}

/// Сколько стека под вызывающим затирает [`wipe_stack_below`], байт.
///
/// Расшифровка чанка и копирование ответа драйверу уходят вглубь на единицы
/// килобайт; замер C2 нашёл открытый текст в пределах 6 КиБ под кадром.
/// Запас на порядок — и не больше: стек потока пула системы — 1 МиБ резерва.
pub const STACK_WIPE_BYTES: usize = 64 * 1024;

/// Затереть стек ПОД текущим кадром — там, где жили кадры уже вернувшихся
/// вызовов.
///
/// Зачем: `SecretBuf` затирает свою память, но расшифровка и копирование
/// проходят через кадры, которые кладут куски открытого текста на стек
/// (временные блоки шифра, копии системных вызовов), а стек при возврате не
/// чистится. Замер C2: после остывания представления в памяти брокера лежали
/// 26 строк документа — все в стеке потока, отдававшего данные драйверу.
///
/// Как: локальный массив той же глубины затирается записью, которую
/// компилятор не вправе убрать (`zeroize`), а функция не встраивается — иначе
/// массив лёг бы в кадр вызывающего, а не под него. Звать ПОСЛЕ работы с
/// открытым текстом и с той же глубины, откуда её звали.
#[inline(never)]
pub fn wipe_stack_below() {
    let mut pad = [0u8; STACK_WIPE_BYTES];
    pad.zeroize();
    core::hint::black_box(&pad);
}

#[cfg(test)]
#[allow(clippy::unwrap_used, clippy::panic)]
mod tests {
    use super::*;

    struct SeqRng(u8);
    impl rand_core::TryRng for SeqRng {
        type Error = core::convert::Infallible;
        fn try_next_u32(&mut self) -> Result<u32, Self::Error> {
            Ok(u32::from(self.0))
        }
        fn try_next_u64(&mut self) -> Result<u64, Self::Error> {
            Ok(u64::from(self.0))
        }
        fn try_fill_bytes(&mut self, dst: &mut [u8]) -> Result<(), Self::Error> {
            for b in dst.iter_mut() {
                self.0 = self.0.wrapping_add(1);
                *b = self.0;
            }
            Ok(())
        }
    }
    impl rand_core::TryCryptoRng for SeqRng {}

    #[test]
    fn debug_never_leaks_the_bytes() {
        // Секрет в логе утекает так же, как записанный на диск.
        let cek = Cek::from_bytes([0xab; SECRET_LEN]);
        let rendered = format!("{cek:?}");
        assert!(!rendered.contains("ab"), "Debug выдал байты секрета: {rendered}");
        assert!(rendered.contains("скрыт"));
    }

    #[test]
    fn random_uses_the_supplied_generator() {
        let mut rng = SeqRng(0);
        let a = Cek::random(&mut rng);
        assert_eq!(a.expose()[0], 1, "генератор должен использоваться, а не подменяться");
        let b = Cek::random(&mut rng);
        assert_ne!(a.expose(), b.expose());
    }

    #[test]
    fn distinct_secret_types_do_not_interchange() {
        // Компиляционное свойство, зафиксированное тестом как намерение: перепутать
        // доли схемы 2-из-2 нельзя, они разных типов.
        let a = SecretA::from_bytes([1; SECRET_LEN]);
        let b = SecretB::from_bytes([1; SECRET_LEN]);
        assert_eq!(a.expose(), b.expose(), "байты совпадают");
        // `let _: SecretA = b;` не компилируется — в этом и смысл.
    }
}
